import { app, type BrowserWindow, clipboard, ipcMain } from "electron";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { randomUUID } from "node:crypto";
import type { ClipHistoryEntry, ClipHistoryState } from "../shared/appSettings";

// Clipboard history for this computer, like CopyClip: text you copy anywhere
// is kept in a local list you can copy from again or send to your devices.
// It never leaves this computer unless you press Send, it's saved in
// <userData>/clip-history.json, and it can be turned off or cleared any time.
// Copies that password managers mark as concealed or temporary are skipped.

const MAX_ENTRIES = 200;
const MAX_CHARS = 10_000;
const POLL_MS = 800;

// Pasteboard types that mean "don't record this" (nspasteboard.org), used by
// 1Password, Bitwarden, KeePassXC, Keychain Access and others.
const SKIP_TYPES = [
  "org.nspasteboard.ConcealedType",
  "org.nspasteboard.TransientType",
  "org.nspasteboard.AutoGeneratedType",
  "com.agilebits.onepassword",
  "de.petermaurer.TransientPasteboardType",
];

let entries: ClipHistoryEntry[] = [];
let enabled = true;
let lastSeen = "";
let timer: NodeJS.Timeout | null = null;
let getWindow: () => BrowserWindow | null = () => null;

function historyPath(): string {
  return join(app.getPath("userData"), "clip-history.json");
}

function load(): void {
  try {
    const saved = JSON.parse(readFileSync(historyPath(), "utf8")) as { enabled?: unknown; entries?: unknown };
    enabled = saved.enabled !== false;
    entries = Array.isArray(saved.entries)
      ? saved.entries
          .filter((e): e is ClipHistoryEntry => !!e && typeof e.id === "string" && typeof e.text === "string" && typeof e.copiedAt === "string")
          .slice(0, MAX_ENTRIES)
      : [];
  } catch {
    enabled = true;
    entries = [];
  }
}

function save(): void {
  try {
    mkdirSync(app.getPath("userData"), { recursive: true });
    writeFileSync(historyPath(), JSON.stringify({ enabled, entries }), "utf8");
  } catch (error: unknown) {
    console.error("Could not save clipboard history:", error);
  }
}

function state(): ClipHistoryState {
  return { enabled, entries };
}

function broadcast(): void {
  getWindow()?.webContents.send("clip-history:changed", state());
}

async function concealed(): Promise<boolean> {
  for (const type of SKIP_TYPES) {
    try {
      if (await clipboard.has(type)) return true;
    } catch {
      // has() is best-effort; fall through
    }
  }
  return false;
}

let polling = false;
async function poll(): Promise<void> {
  if (polling) return;
  polling = true;
  try {
    await readOnce();
  } finally {
    polling = false;
  }
}

async function readOnce(): Promise<void> {
  let text: string;
  try {
    text = await clipboard.readText();
  } catch {
    return;
  }
  if (text === lastSeen || !enabled) return;
  lastSeen = text;
  if (!text.trim() || text.length > MAX_CHARS || (await concealed())) return;
  const existing = entries.find((entry) => entry.text === text);
  entries = [
    { id: existing?.id ?? randomUUID(), text, copiedAt: new Date().toISOString(), pinned: existing?.pinned },
    ...entries.filter((entry) => entry.text !== text),
  ];
  // Pinned entries are never dropped to make room.
  if (entries.length > MAX_ENTRIES) {
    const pinned = entries.filter((entry) => entry.pinned);
    const rest = entries.filter((entry) => !entry.pinned).slice(0, Math.max(0, MAX_ENTRIES - pinned.length));
    entries = entries.filter((entry) => entry.pinned || rest.includes(entry));
  }
  save();
  broadcast();
}

function setWatching(on: boolean): void {
  if (timer) {
    clearInterval(timer);
    timer = null;
  }
  if (on) {
    // What's on the clipboard when history starts isn't a new copy.
    void Promise.resolve(clipboard.readText())
      .then((text) => { lastSeen = text; })
      .catch(() => { lastSeen = ""; })
      .finally(() => {
        if (enabled && !timer) timer = setInterval(() => void poll(), POLL_MS);
      });
  }
}

// Account deleted on this computer: forget everything.
export function clearClipHistory(): void {
  entries = [];
  save();
  broadcast();
}

export function setupClipHistory(windowGetter: () => BrowserWindow | null): void {
  getWindow = windowGetter;
  load();
  setWatching(enabled);
  app.on("will-quit", () => setWatching(false));

  ipcMain.handle("clip-history:get", () => state());
  ipcMain.handle("clip-history:set-enabled", (_event, on: unknown) => {
    enabled = on === true;
    setWatching(enabled);
    save();
    broadcast();
    return state();
  });
  ipcMain.handle("clip-history:remove", (_event, id: unknown) => {
    entries = entries.filter((entry) => entry.id !== id);
    save();
    broadcast();
    return state();
  });
  ipcMain.handle("clip-history:pin", (_event, id: unknown, pinned: unknown) => {
    entries = entries.map((entry) => (entry.id === id ? { ...entry, pinned: pinned === true || undefined } : entry));
    save();
    broadcast();
    return state();
  });
  ipcMain.handle("clip-history:clear", () => {
    // Clearing keeps pinned entries, like other clipboard managers.
    entries = entries.filter((entry) => entry.pinned);
    save();
    broadcast();
    return state();
  });
}

